const puppeteer = require("puppeteer")
const fs = require("fs")

// Find an installed Chromium-based browser (same logic as ai.service.js)
const CANDIDATE_BROWSERS = [
    process.env.PUPPETEER_EXECUTABLE_PATH,
    "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe",
    "C:\\Program Files (x86)\\Google\\Chrome\\Application\\chrome.exe",
    "C:\\Program Files\\Microsoft\\Edge\\Application\\msedge.exe",
    "C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe",
    "/usr/bin/google-chrome",
    "/usr/bin/google-chrome-stable",
    "/usr/bin/chromium",
    "/usr/bin/chromium-browser",
    "/usr/bin/microsoft-edge",
].filter(Boolean)

function getBrowserExecutable() {
    for (const p of CANDIDATE_BROWSERS) {
        try {
            if (fs.existsSync(p)) return p
        } catch { /* ignore */ }
    }
    return null
}

/**
 * Escape HTML entities for safe rendering in the export HTML.
 */
function escapeHtml(str) {
    if (typeof str !== "string") return ""
    return str
        .replace(/&/g, function() { return "&" + "amp;" })
        .replace(/</g, function() { return "&" + "lt;" })
        .replace(/>/g, function() { return "&" + "gt;" })
        .replace(/"/g, function() { return "&" + "quot;" })
        .replace(/'/g, function() { return "&" + "#39;" })
}

/**
 * @name generatePdfFromHtml
 * @description Convert HTML to a PDF buffer using installed Chrome/Edge or bundled Chromium.
 */
async function generatePdfFromHtml(htmlContent) {
    const executablePath = getBrowserExecutable()
    const launchOptions = executablePath ? { executablePath } : {}
    const browser = await puppeteer.launch(launchOptions)

    try {
        const page = await browser.newPage()
        await page.setContent(htmlContent, { waitUntil: "networkidle0" })

        const pdfResult = await page.pdf({
            format: "A4",
            margin: {
                top: "20mm",
                bottom: "20mm",
                left: "15mm",
                right: "15mm"
            }
        })

        const pdfBuffer = Buffer.from(pdfResult)

        if (pdfBuffer.length === 0) {
            throw new Error("PDF generation returned an empty buffer.")
        }

        return pdfBuffer
    } finally {
        await browser.close()
    }
}

