/**
 * @name exportInterviewReport
 * @description Export an interview report as PDF.
 */
async function exportInterviewReport(report) {
    const skillGaps = (report.skillGaps || []).map(g =>
        `<li>${escapeHtml(g.skill)} <span class="meta">(${escapeHtml(g.severity)} priority)</span></li>`
    ).join("")

    const technicalQuestions = (report.technicalQuestions || []).map((q, i) =>
        `<div class="section">
            <h3>Q${i + 1}: ${escapeHtml(q.question)}</h3>
            <p class="meta"><strong>Intention:</strong> ${escapeHtml(q.intention)}</p>
            <p><strong>Suggested approach:</strong> ${escapeHtml(q.answer)}</p>
        </div>`
    ).join("")

    const behavioralQuestions = (report.behavioralQuestions || []).map((q, i) =>
        `<div class="section">
            <h3>Q${i + 1}: ${escapeHtml(q.question)}</h3>
            <p class="meta"><strong>Intention:</strong> ${escapeHtml(q.intention)}</p>
            <p><strong>Suggested approach:</strong> ${escapeHtml(q.answer)}</p>
        </div>`
    ).join("")

    const prepPlan = (report.preparationPlan || []).map(p =>
        `<div class="section">
            <h3>Day ${p.day}: ${escapeHtml(p.focus)}</h3>
            <ul>${(p.tasks || []).map(t => `<li>${escapeHtml(t)}</li>`).join("")}</ul>
        </div>`
    ).join("")

    const bodyHtml = `
        <h1>Interview Report</h1>
        <p class="meta">${escapeHtml(report.title || "")}</p>

        <div class="info-grid">
            <div class="info-card"><strong>Match Score</strong><span class="score-badge">${report.matchScore ?? "N/A"}/100</span></div>
            <div class="info-card"><strong>Generated</strong><span>${new Date(report.createdAt).toLocaleDateString()}</span></div>
        </div>

        <h2>Skill Gaps</h2>
        ${skillGaps ? `<ul>${skillGaps}</ul>` : "<p class='meta'>No skill gaps identified.</p>"}

        <h2>Technical Questions</h2>
        ${technicalQuestions || "<p class='meta'>None generated.</p>"}

        <h2>Behavioral Questions</h2>
        ${behavioralQuestions || "<p class='meta'>None generated.</p>"}

        <h2>Preparation Plan</h2>
        ${prepPlan || "<p class='meta'>No preparation plan generated.</p>"}
    `

    return generatePdfFromHtml(baseHtml(`Interview Report - ${report.title || ""}`, bodyHtml))
}

/**
 * @name exportChat
 * @description Export a chat conversation as PDF.
 */
async function exportChat(chat) {
    const messages = (chat.messages || []).map(m => {
        const role = m.role === "user" ? "Candidate" : "AI Coach"
        return `
            <div class="section">
                <p class="meta"><strong>${role}</strong> &middot; ${new Date(m.createdAt).toLocaleString()}</p>
                <div><pre>${escapeHtml(m.content)}</pre></div>
            </div>
        `
    }).join("")

    const bodyHtml = `
        <h1>Chat Conversation</h1>
        <p class="meta">${escapeHtml(chat.title || "Untitled Chat")}</p>
        ${messages || "<p class='meta'>No messages.</p>"}
    `

    return generatePdfFromHtml(baseHtml(`Chat - ${chat.title || "Conversation"}`, bodyHtml))
}

/**
 * @name exportMockInterview
 * @description Export a mock interview session as PDF.
 */
async function exportMockInterview(session) {
    const questions = (session.questions || []).map((q, i) => {
        const evalScore = q.evaluation?.score !== null && q.evaluation?.score !== undefined ? `${q.evaluation.score}/10` : "N/A"
        return `
            <div class="section">
                <h3>Q${i + 1}: ${escapeHtml(q.question)}</h3>
                <p><strong>Answer:</strong> ${escapeHtml(q.answer || "No answer")}</p>
                <p><strong>Score:</strong> <span class="score-badge">${evalScore}</span></p>
                ${q.evaluation?.strengths?.length ? `<p><strong>Strengths:</strong></p><ul>${q.evaluation.strengths.map(s => `<li>${escapeHtml(s)}</li>`).join("")}</ul>` : ""}
                ${q.evaluation?.weaknesses?.length ? `<p><strong>Weaknesses:</strong></p><ul>${q.evaluation.weaknesses.map(w => `<li>${escapeHtml(w)}</li>`).join("")}</ul>` : ""}
                ${q.evaluation?.betterAnswer ? `<p><strong>Better Answer:</strong> ${escapeHtml(q.evaluation.betterAnswer)}</p>` : ""}
                ${q.evaluation?.tips?.length ? `<p><strong>Tips:</strong></p><ul>${q.evaluation.tips.map(t => `<li>${escapeHtml(t)}</li>`).join("")}</ul>` : ""}
            </div>
        `
    }).join("")

    const answered = (session.questions || []).filter(q => q.answer).length
    const scores = (session.questions || [])
        .map(q => q.evaluation?.score)
        .filter(s => s !== null && s !== undefined)
    const avgScore = scores.length > 0 ? Math.round(scores.reduce((a, b) => a + b, 0) / scores.length) : "N/A"

    const bodyHtml = `
        <h1>Mock Interview Report</h1>
        <p class="meta">${escapeHtml(session.type)} interview</p>

        <div class="info-grid">
            <div class="info-card"><strong>Duration</strong><span>${session.durationMin || 30} min</span></div>
            <div class="info-card"><strong>Questions Answered</strong><span>${answered}</span></div>
            <div class="info-card"><strong>Average Score</strong><span class="score-badge">${avgScore}</span></div>
        </div>

        <h2>Questions &amp; Evaluations</h2>
        ${questions || "<p class='meta'>No questions.</p>"}
    `

    return generatePdfFromHtml(baseHtml(`Mock Interview - ${session.type}`, bodyHtml))
}

/**
 * @name exportRoadmap
 * @description Export a career roadmap as PDF.
 */
async function exportRoadmap(roadmap) {
    const weeks = (roadmap.weeks || []).map(w =>
        `<div class="section">
            <h3>Week ${w.week}: ${escapeHtml(w.title)}</h3>
            <p class="meta"><strong>Focus:</strong> ${escapeHtml(w.focus)}</p>
            <p><strong>Tasks:</strong></p>
            <ul>${(w.tasks || []).map(t => `<li>${escapeHtml(t)}</li>`).join("")}</ul>
            ${w.resources?.length ? `<p><strong>Resources:</strong></p><ul>${w.resources.map(r => `<li>${escapeHtml(r)}</li>`).join("")}</ul>` : ""}
        </div>`
    ).join("")

    const bodyHtml = `
        <h1>Career Roadmap</h1>
        <p class="meta">${escapeHtml(roadmap.title || "Career Roadmap")}</p>
        ${roadmap.summary ? `<p>${escapeHtml(roadmap.summary)}</p>` : ""}
        ${weeks || "<p class='meta'>No weeks generated.</p>"}
    `

    return generatePdfFromHtml(baseHtml(`Roadmap - ${roadmap.title || "Career"}`, bodyHtml))
}

module.exports = {
    exportInterviewReport,
    exportChat,
    exportMockInterview,
    exportRoadmap,
    generatePdfFromHtml,
    escapeHtml
}
